/**
 * Belirtilen sınıf ve ünite adı için eşleşen içerik çerçevesini getirir.
 * Eşleşme esnek (lowercase & substring) olarak yapılır.
 */
function getCerceve(sinif, unite) {
  if (!sinif || !unite) return null;
  
  const cleanedUnite = unite.trim().toLowerCase();
  const classFrames = ICERIK_CERCEVELERI[sinif];
  
  if (classFrames) {
    for (let uKey in classFrames) {
      const cleanedKey = uKey.trim().toLowerCase();
      if (cleanedUnite.includes(cleanedKey) || cleanedKey.includes(cleanedUnite)) {
        return classFrames[uKey];
      }
    }
  }
  return null;
}
