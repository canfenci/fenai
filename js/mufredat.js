function getOzelMufre() {
  const raw = localStorage.getItem('mufre_ozel');
  return raw ? JSON.parse(raw) : {};
}

function setOzelMufre(data) {
  localStorage.setItem('mufre_ozel', JSON.stringify(data));
}

function getMufre() {
  const varsayilan = MUFRE;
  const ozel = getOzelMufre();
  const birlesik = {};
  for (let sinif of ['5','6','7','8']) {
    birlesik[sinif] = {};
    if (varsayilan[sinif]) {
      for (let unite in varsayilan[sinif]) {
        birlesik[sinif][unite] = [...varsayilan[sinif][unite]];
      }
    }
    if (ozel[sinif]) {
      for (let unite in ozel[sinif]) {
        if (birlesik[sinif][unite]) {
          const mevcut = new Set(birlesik[sinif][unite]);
          ozel[sinif][unite].forEach(k => mevcut.add(k));
          birlesik[sinif][unite] = Array.from(mevcut);
        } else {
          birlesik[sinif][unite] = [...ozel[sinif][unite]];
        }
      }
    }
  }
  return birlesik;
}

function loadUnits(prefix) {
  const sinifId = prefix.startsWith('deneme') ? 'deneme-sinif' : prefix + '-sinif';
  const sinifEl = document.getElementById(sinifId);
  if (!sinifEl) return;
  const sinif = sinifEl.value;
  const uniteEl = document.getElementById(prefix + '-unite');
  uniteEl.innerHTML = '';
  const mufre = getMufre();
  const uniteler = mufre[sinif] || {};
  Object.keys(uniteler).forEach(u => {
    const opt = document.createElement('option');
    opt.value = u; opt.textContent = u;
    uniteEl.appendChild(opt);
  });
  loadTopics(prefix);
}

function loadTopics(prefix) {
  const sinifId = prefix.startsWith('deneme') ? 'deneme-sinif' : prefix + '-sinif';
  const sinifEl = document.getElementById(sinifId);
  if (!sinifEl) return;
  const sinif = sinifEl.value;
  const unite = document.getElementById(prefix + '-unite').value;
  const topicEl = document.getElementById(prefix + '-topic');
  topicEl.innerHTML = '';
  const mufre = getMufre();
  const topics = (mufre[sinif] && mufre[sinif][unite]) || [];
  
  // Konuları temiz adına göre grupla
  const grouped = {};
  topics.forEach(t => {
    const cleanName = t.includes(' - ') ? t.split(' - ')[0] : t;
    if (!grouped[cleanName]) {
      grouped[cleanName] = [];
    }
    grouped[cleanName].push(t);
  });
  
  // Gruplanmış konuları açılır menüye ekle
  Object.keys(grouped).forEach(cleanName => {
    const opt = document.createElement('option');
    opt.textContent = cleanName;
    
    if (grouped[cleanName].length === 1) {
      opt.value = grouped[cleanName][0];
    } else {
      // Birden fazla öğrenme çıktısı varsa açıklamaları birleştir
      const mergedDetails = grouped[cleanName].map(t => {
        const idx = t.indexOf(' - ');
        return idx !== -1 ? t.substring(idx + 3) : t;
      }).join(' VE ');
      opt.value = `${cleanName} - [KAPSAMLI KAZANIMLAR]: ${mergedDetails}`;
    }
    topicEl.appendChild(opt);
  });
  if (prefix === 'yaz') {
    loadCiktilar();
  } else if (prefix === 'deneme-konu') {
    loadDenemeKonuCiktilar();
  } else if (prefix === 'deneme-ogr') {
    loadDenemeOgrCiktilar();
  }
}

function loadCiktilar() {
  const sinifEl = document.getElementById('yaz-sinif');
  if (!sinifEl) return;
  const sinif = sinifEl.value;
  const uniteEl = document.getElementById('yaz-unite');
  if (!uniteEl) return;
  const unite = uniteEl.value;
  const topicEl = document.getElementById('yaz-topic');
  if (!topicEl) return;
  const topic = topicEl.value;
  const ciktiEl = document.getElementById('yaz-cikti');
  if (!ciktiEl) return;
  ciktiEl.innerHTML = '';
  
  const mufre = getMufre();
  const topics = (mufre[sinif] && mufre[sinif][unite]) || [];
  
  const cleanSelectedName = topic.includes(' - ') ? topic.split(' - ')[0] : topic;
  
  topics.forEach(t => {
    const cleanName = t.includes(' - ') ? t.split(' - ')[0] : t;
    if (cleanName === cleanSelectedName) {
      const opt = document.createElement('option');
      opt.value = t;
      opt.textContent = t;
      ciktiEl.appendChild(opt);
    }
  });
}

function refreshAllUnits() {
  ['konu','test','bag','ck','yaz','deneme-konu','deneme-ogr'].forEach(p => {
    const sinifEl = document.getElementById(p + '-sinif');
    if (sinifEl) {
      const val = sinifEl.value;
      loadUnits(p);
      sinifEl.value = val;
      loadTopics(p);
    }
  });
}

