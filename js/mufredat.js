function mufreSinifDegisti() {
  const sinif = document.getElementById('mufre-sinif').value;
  const container = document.getElementById('mufre-uniteler-container');
  const mufre = getMufre();
  const uniteler = mufre[sinif] || {};
  let html = `<div style="margin-bottom:12px; font-weight:600; color:var(--text-muted);">Mevcut Üniteler ve Konular:</div>`;
  for (let unite in uniteler) {
    const konular = uniteler[unite];
    html += `<div style="background:var(--surface2); padding:10px; border-radius:8px; margin-bottom:8px; border:1px solid var(--border);">
              <div style="display:flex; justify-content:space-between; align-items:center;">
                <strong style="color:var(--primary);">${unite}</strong>
                <button class="btn btn-danger btn-sm" onclick="mufreUniteSil('${sinif}','${unite}')">✕</button>
              </div>
              <ul style="margin:6px 0 0 20px; font-size:0.85rem; color:var(--text-muted);">
                ${konular.map(k => `<li>${k} <button class="btn btn-danger btn-sm" style="padding:0 6px; font-size:0.6rem;" onclick="mufreKonuSil('${sinif}','${unite}','${k}')">✕</button></li>`).join('')}
              </ul>
            </div>`;
  }
  html += `<div style="margin-top:8px; font-size:0.8rem; color:var(--text-muted);">📌 Varsayılan müfredat + özel eklemeleriniz gösteriliyor.</div>`;
  container.innerHTML = html;
  mufreUniteSelectGuncelle();
}

function mufreUniteSelectGuncelle() {
  const sinif = document.getElementById('mufre-sinif').value;
  const mufre = getMufre();
  const uniteler = Object.keys(mufre[sinif] || {});
  const select = document.getElementById('mufre-unite-select');
  if (!select) return;
  select.innerHTML = '';
  uniteler.forEach(u => {
    const opt = document.createElement('option');
    opt.value = u;
    opt.textContent = u;
    select.appendChild(opt);
  });
}

function mufreUniteEkle() {
  const sinif = document.getElementById('mufre-sinif').value;
  const uniteAdi = document.getElementById('mufre-yeni-unite').value.trim();
  if (!uniteAdi) { showToast('Ünite adı boş olamaz.', 'error'); return; }
  const ozel = getOzelMufre();
  if (!ozel[sinif]) ozel[sinif] = {};
  if (ozel[sinif][uniteAdi]) { showToast('Bu ünite zaten mevcut.', 'error'); return; }
  ozel[sinif][uniteAdi] = [];
  setOzelMufre(ozel);
  document.getElementById('mufre-yeni-unite').value = '';
  mufreSinifDegisti();
  showToast(`"${uniteAdi}" ünitesi eklendi.`, 'success');
  refreshAllUnits();
}

function mufreKonuEkle() {
  const sinif = document.getElementById('mufre-sinif').value;
  const unite = document.getElementById('mufre-unite-select').value;
  const konu = document.getElementById('mufre-yeni-konu').value.trim();
  if (!konu) { showToast('Konu açıklaması boş olamaz.', 'error'); return; }
  if (!unite) { showToast('Lütfen bir ünite seçin.', 'error'); return; }
  const ozel = getOzelMufre();
  if (!ozel[sinif]) ozel[sinif] = {};
  if (!ozel[sinif][unite]) ozel[sinif][unite] = [];
  if (ozel[sinif][unite].includes(konu)) { showToast('Bu konu zaten mevcut.', 'error'); return; }
  ozel[sinif][unite].push(konu);
  setOzelMufre(ozel);
  document.getElementById('mufre-yeni-konu').value = '';
  mufreSinifDegisti();
  showToast(`"${konu}" konusu eklendi.`, 'success');
  refreshAllUnits();
}

function mufreUniteSil(sinif, unite) {
  if (!confirm(`"${unite}" ünitesini silmek istediğinize emin misiniz?`)) return;
  const ozel = getOzelMufre();
  if (ozel[sinif] && ozel[sinif][unite]) {
    delete ozel[sinif][unite];
    setOzelMufre(ozel);
    mufreSinifDegisti();
    showToast(`"${unite}" silindi.`, 'info');
    refreshAllUnits();
  }
}

function mufreKonuSil(sinif, unite, konu) {
  if (!confirm(`"${konu}" konusunu silmek istediğinize emin misiniz?`)) return;
  const ozel = getOzelMufre();
  if (ozel[sinif] && ozel[sinif][unite]) {
    const idx = ozel[sinif][unite].indexOf(konu);
    if (idx > -1) {
      ozel[sinif][unite].splice(idx, 1);
      setOzelMufre(ozel);
      mufreSinifDegisti();
      showToast(`"${konu}" silindi.`, 'info');
      refreshAllUnits();
    }
  }
}

function mufreSifirla() {
  if (!confirm('Tüm özel müfredat eklemeleriniz silinecek. Varsayılan müfredat kalacak. Emin misiniz?')) return;
  localStorage.removeItem('mufre_ozel');
  mufreSinifDegisti();
  showToast('Özel eklemeler sıfırlandı.', 'info');
  refreshAllUnits();
}

